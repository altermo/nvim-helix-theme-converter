local function tree_with_fallbacks(fallbacks)
  return function(recursive,key)
    local hl_info=recursive('@'..key)
    for _,v in ipairs(fallbacks) do
      if not vim.tbl_isempty(hl_info) then
        return hl_info
      end
      hl_info=recursive(v)
    end
    return hl_info
  end
end
